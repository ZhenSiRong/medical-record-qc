-- ============================================================
-- 病案管理系统 mrs 表结构（V2.1，PostgreSQL，表结构唯一事实来源）
-- GORM 实体与之一一对应（internal/model）。
-- Docker 部署时由 postgres 镜像 /docker-entrypoint-initdb.d 自动执行；
-- 业务库 mrs 由 POSTGRES_DB 环境变量创建，本文件不含 CREATE DATABASE。
-- updated_at 的更新由 GORM 统一维护，PG 侧不做 ON UPDATE 触发器。
-- ============================================================

-- ---------- 病案域 ----------

-- 病案主档（全系统锚点，status 驱动主状态机）
CREATE TABLE IF NOT EXISTS med_record (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_no      VARCHAR(32)  NOT NULL,            -- 病案号（唯一）
  patient_name   VARCHAR(64)  NOT NULL,            -- 患者姓名
  gender         VARCHAR(8),                      -- 性别：男/女
  birth_date     DATE,                            -- 出生日期
  hospital_no    VARCHAR(32),                     -- 住院号
  dept_id        BIGINT,                          -- 出院科室ID
  dept_name      VARCHAR(64),                     -- 出院科室名（快照）
  doctor_name    VARCHAR(64),                     -- 主治医师
  admit_time     TIMESTAMP,                       -- 入院时间
  discharge_time TIMESTAMP,                       -- 出院时间
  status         VARCHAR(16)  NOT NULL DEFAULT 'NOT_RECYCLED', -- NOT_RECYCLED未回收/RECYCLED已回收/CATALOGED已编目/ARCHIVED已归档/BORROWED借出/SEALED封存
  shelf_id       BIGINT,                          -- 当前架位
  remark         VARCHAR(255),
  created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_record_no ON med_record (record_no);
CREATE INDEX IF NOT EXISTS idx_mr_status ON med_record (status);
CREATE INDEX IF NOT EXISTS idx_mr_dept ON med_record (dept_id);

-- 病案首页（住院病案首页规范字段骨架集 + 扩展JSON）
CREATE TABLE IF NOT EXISTS med_record_front_page (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_id             BIGINT       NOT NULL,
  patient_name          VARCHAR(64),
  gender                VARCHAR(8),
  birth_date            DATE,
  hospital_no           VARCHAR(32),
  dept_name             VARCHAR(64),
  doctor_name           VARCHAR(64),
  admit_time            TIMESTAMP,               -- 入院时间
  discharge_time        TIMESTAMP,               -- 出院时间
  actual_days           INT,                     -- 实际住院天数
  admit_diagnosis       VARCHAR(255),            -- 入院诊断
  discharge_diagnosis   VARCHAR(255),            -- 出院诊断
  main_diagnosis_code   VARCHAR(32),             -- 主要诊断编码(ICD-10)
  other_diagnosis_codes VARCHAR(500),            -- 其他诊断编码，逗号分隔
  main_operation_code   VARCHAR(32),             -- 主要手术编码(ICD-9-CM3)
  other_operation_codes VARCHAR(500),            -- 其他手术编码，逗号分隔
  total_cost            NUMERIC(12,2),           -- 住院总费用
  ext_json              TEXT,                    -- 上报规范其余字段暂存
  status                VARCHAR(16) NOT NULL DEFAULT 'DRAFT', -- DRAFT/WAIT_QC/QC_PASSED/QC_REJECTED/REPORTED
  created_at            TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at            TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_fp_record ON med_record_front_page (record_id);
CREATE INDEX IF NOT EXISTS idx_fp_status ON med_record_front_page (status);

-- 首页质控结果（逐字段异常标记）
CREATE TABLE IF NOT EXISTS front_page_qc_result (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_id   BIGINT       NOT NULL,
  rule_id     BIGINT,
  field_name  VARCHAR(64)  NOT NULL,
  error_level VARCHAR(8)   NOT NULL DEFAULT 'ERROR', -- ERROR/WARN
  error_msg   VARCHAR(255) NOT NULL,
  fixed       BOOLEAN      NOT NULL DEFAULT FALSE,
  fixed_at    TIMESTAMP,
  fixed_by    VARCHAR(64),
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_qcr_record ON front_page_qc_result (record_id);

-- 质控规则（可配置，规则清单来自调研输出）
CREATE TABLE IF NOT EXISTS qc_rule (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rule_name    VARCHAR(64)  NOT NULL,
  rule_type    VARCHAR(16)  NOT NULL,   -- REQUIRED必填/LOGIC逻辑/CODE_EXIST编码存在性
  target_field VARCHAR(64)  NOT NULL,   -- Go 结构体字段名，如 MainDiagnosisCode
  expression   VARCHAR(255),            -- LOGIC: discharge_time>admit_time；CODE_EXIST: ICD10/ICD9CM3
  error_level  VARCHAR(8)   NOT NULL DEFAULT 'ERROR',
  enabled      BOOLEAN      NOT NULL DEFAULT TRUE,
  remark       VARCHAR(255),
  created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 归档流水（回收/归档/封存留痕，批量操作按明细落流水）
CREATE TABLE IF NOT EXISTS archive_record (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_id     BIGINT       NOT NULL,
  action        VARCHAR(16)  NOT NULL,   -- RECYCLE/ARCHIVE/SEAL
  batch_no      VARCHAR(32),
  shelf_id      BIGINT,
  operator_name VARCHAR(64),
  remark        VARCHAR(255),
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ar_record ON archive_record (record_id);
CREATE INDEX IF NOT EXISTS idx_ar_batch ON archive_record (batch_no);

-- 架位
CREATE TABLE IF NOT EXISTS shelf (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelf_code    VARCHAR(32)  NOT NULL,
  room          VARCHAR(64),
  location_desc VARCHAR(128),
  capacity      INT NOT NULL DEFAULT 0,
  used_count    INT NOT NULL DEFAULT 0,
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_shelf_code ON shelf (shelf_code);

-- 编目记录（一条病案多条诊断/手术）
CREATE TABLE IF NOT EXISTS catalog_entry (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_id    BIGINT       NOT NULL,
  catalog_type VARCHAR(16)  NOT NULL,   -- DIAGNOSIS/OPERATION
  icd_code     VARCHAR(32)  NOT NULL,
  icd_name     VARCHAR(128),
  is_main      BOOLEAN      NOT NULL DEFAULT FALSE,
  sort_order   INT          NOT NULL DEFAULT 0,
  coder_name   VARCHAR(64),
  created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ce_record ON catalog_entry (record_id);
CREATE INDEX IF NOT EXISTS idx_ce_code ON catalog_entry (icd_code);

-- ICD 编码字典（支持整版换版）
CREATE TABLE IF NOT EXISTS icd_dict (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dict_type  VARCHAR(16)  NOT NULL,    -- ICD10/ICD9CM3
  code       VARCHAR(32)  NOT NULL,
  name       VARCHAR(128) NOT NULL,
  version_id BIGINT,
  enabled    BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_icd_type_code ON icd_dict (dict_type, code);
CREATE INDEX IF NOT EXISTS idx_icd_name ON icd_dict (name);

CREATE TABLE IF NOT EXISTS icd_dict_version (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version       VARCHAR(32) NOT NULL,
  dict_type     VARCHAR(16) NOT NULL,
  importer_name VARCHAR(64),
  total_count   INT NOT NULL DEFAULT 0,
  status        VARCHAR(16) NOT NULL DEFAULT 'ACTIVE', -- ACTIVE/HISTORY
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ---------- 借阅域 ----------

CREATE TABLE IF NOT EXISTS borrow_order (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_no      VARCHAR(32)  NOT NULL,
  record_id     BIGINT       NOT NULL,
  record_no     VARCHAR(32),             -- 病案号（快照）
  borrower_name VARCHAR(64)  NOT NULL,
  borrower_dept VARCHAR(64),
  reason        VARCHAR(255) NOT NULL,
  urgent        BOOLEAN      NOT NULL DEFAULT FALSE,
  status        VARCHAR(16)  NOT NULL DEFAULT 'APPLYING', -- APPLYING/APPROVED/REJECTED/BORROWED/OVERDUE/RETURNED
  apply_time    TIMESTAMP,
  lend_time     TIMESTAMP,
  due_time      TIMESTAMP,               -- 应还时间
  return_time   TIMESTAMP,               -- 实还时间（归还核销）
  handler_name  VARCHAR(64),             -- 病案室经办人
  remark        VARCHAR(255),
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_order_no ON borrow_order (order_no);
CREATE INDEX IF NOT EXISTS idx_bo_status ON borrow_order (status);
CREATE INDEX IF NOT EXISTS idx_bo_due ON borrow_order (due_time);

CREATE TABLE IF NOT EXISTS borrow_approval (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      BIGINT       NOT NULL,
  level         INT          NOT NULL DEFAULT 1, -- 第几级审批
  approver_name VARCHAR(64)  NOT NULL,
  result        VARCHAR(8)   NOT NULL,           -- APPROVED/REJECTED
  opinion       VARCHAR(255),
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ba_order ON borrow_approval (order_id);

CREATE TABLE IF NOT EXISTS borrow_reminder (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   BIGINT       NOT NULL,
  channel    VARCHAR(16)  NOT NULL DEFAULT 'SYSTEM',
  result     VARCHAR(64),
  remark     VARCHAR(255),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_br_order ON borrow_reminder (order_id);

-- ---------- 上报域 ----------

CREATE TABLE IF NOT EXISTS report_batch (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_no      VARCHAR(32)  NOT NULL,
  period        VARCHAR(16)  NOT NULL,   -- 如 2026-08
  status        VARCHAR(16)  NOT NULL DEFAULT 'PENDING', -- PENDING/SUCCESS/FAILED/PARTIAL
  total_count   INT NOT NULL DEFAULT 0,
  success_count INT NOT NULL DEFAULT 0,
  fail_count    INT NOT NULL DEFAULT 0,
  submit_time   TIMESTAMP,
  operator_name VARCHAR(64),
  remark        VARCHAR(255),
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_batch_no ON report_batch (batch_no);

CREATE TABLE IF NOT EXISTS report_item (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id       BIGINT       NOT NULL,
  record_id      BIGINT       NOT NULL,
  receipt_status VARCHAR(16)  NOT NULL DEFAULT 'WAITING', -- WAITING/SUCCESS/FAIL
  receipt_msg    VARCHAR(500),                            -- 回执信息/失败原因（排查用）
  receipt_time   TIMESTAMP,
  created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_ri_batch_record ON report_item (batch_id, record_id);

-- ---------- 系统域 ----------

CREATE TABLE IF NOT EXISTS sys_dept (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dept_code  VARCHAR(32) NOT NULL,
  dept_name  VARCHAR(64) NOT NULL,
  enabled    BOOLEAN     NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_dept_code ON sys_dept (dept_code);

-- V2.1 简化：用户挂单角色 role_code，多角色需求出现时再引入 sys_user_role
CREATE TABLE IF NOT EXISTS sys_user (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username   VARCHAR(32)  NOT NULL,
  password   VARCHAR(128) NOT NULL,     -- bcrypt
  real_name  VARCHAR(64),
  dept_id    BIGINT,
  dept_name  VARCHAR(64),
  phone      VARCHAR(32),
  role_code  VARCHAR(32)  NOT NULL DEFAULT 'DEPT_USER', -- ADMIN/DEPT_USER
  enabled    BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_username ON sys_user (username);

CREATE TABLE IF NOT EXISTS sys_role (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_code  VARCHAR(32)  NOT NULL,
  role_name  VARCHAR(64)  NOT NULL,
  data_scope VARCHAR(16)  NOT NULL DEFAULT 'DEPT', -- 数据权限：ALL全院/DEPT本科室
  remark     VARCHAR(255),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_role_code ON sys_role (role_code);

CREATE TABLE IF NOT EXISTS sys_doctor (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_code VARCHAR(32) NOT NULL,
  doctor_name VARCHAR(64) NOT NULL,
  dept_id     BIGINT,
  dept_name   VARCHAR(64),
  title       VARCHAR(32),
  enabled     BOOLEAN     NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_doctor_code ON sys_doctor (doctor_code);

CREATE TABLE IF NOT EXISTS sys_dict (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dict_type  VARCHAR(32)  NOT NULL,
  dict_key   VARCHAR(32)  NOT NULL,
  dict_value VARCHAR(128) NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_sd_type ON sys_dict (dict_type);

CREATE TABLE IF NOT EXISTS oper_log (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module        VARCHAR(32),   -- 模块（路径首段）
  operation     VARCHAR(64),   -- 操作（HTTP方法+路径）
  operator_name VARCHAR(64),
  ip            VARCHAR(64),
  status_code   INT,
  cost_ms       INT,
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ol_created ON oper_log (created_at);
