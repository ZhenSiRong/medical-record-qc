// Package bdd 承载本项目的「行为规范可执行化」层。
//
// # 定位与权威层级（重要）
//
// 本项目的行为描述集中在两处权威源，本层**不重新发明规则**：
//
//   - 领域行为（状态机）：SPEC.md §2.2「三条状态机」——病案主状态机、
//     借阅子状态机、首页质控与上报子状态机（含 OPEN→RETURNED→RECTIFIED→CLOSED 闭环）。
//   - 接口行为（契约）：mrs-backend/docs/API.md——每个端点的语义、
//     状态码条件（400/401/403/409）、字段契约与「全量赋值」约定。
//
// 本目录与 ../features 下的 .feature 文件只做上面两者的**可执行化引用**：
// 把已经定稿的规则翻译成机器可跑的场景。若 .feature 与权威源冲突，
// **以权威源为准并修正 .feature**，不得反过来用 .feature 定义业务规则。
//
// # 为什么用 godog 而不是 pytest-bdd
//
// 本项目的测试门禁是 `go test ./... -count=1`。godog 让行为场景留在同一条门禁内，
// 不新增语言、工具链与 CI 环节，并可直接复用 router.Register、middleware.SignToken
// 等既有基建。若将来需要「活服务 + 真库」的黑盒验收层，可另起 pytest-bdd
// 引用同一批 .feature 文件——Gherkin 与 runner 是解耦的，不必二选一。
//
// 注意：pytest-bdd 那条路需要 PostgreSQL 与应用进程同时在线（本仓库无 sqlite 驱动，
// 纯内存跑不了），因此它是「非自足（non-hermetic）」的；godog 这一层则是自足的。
//
// # 断言层级
//
// 当前场景统一在 HTTP 层断言，且挂载**真实全量路由树**（含真实中间件链），
// 但 db=nil 不连库：非法请求在碰库之前被拒（400/401/403），
// 合法请求越过校验后在 h.DB 处 panic（被测试的静默 Recovery 兑现为 500）。
// 每个 .feature 文件头部都写明了这套「无数据库桩」约定，避免后人误读 500。
//
// 本目录只含测试代码与套件装配，真正的场景在 bdd_test.go。
